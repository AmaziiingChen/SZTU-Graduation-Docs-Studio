// Regenerate tests/fixtures/bibtex-rendering.golden.json from the repository
// GB/T 7714—2025 style, so the desktop preview can be held to the same
// punctuation and field order that the compiled PDF produces.
//
// Usage:
//   node scripts/generate_bibtex_rendering_golden.mjs
//   SZTU_BIBTEX_PATH="C:\path\to\bibtex.exe" node scripts/generate_bibtex_rendering_golden.mjs
//   SZTU_TEMPLATE_DIR="C:\path\to\Thesis" node scripts/generate_bibtex_rendering_golden.mjs
//
// The style file is taken from the template checkout, not from the TeX
// distribution: local punctuation changes (control.bib.punct = "bylanguage")
// only exist in the template copy.
import { execFile } from "node:child_process"
import { createHash } from "node:crypto"
import { access, copyFile, mkdir, readFile, readdir, writeFile } from "node:fs/promises"
import path from "node:path"
import { promisify } from "node:util"
import { fileURLToPath } from "node:url"

const run = promisify(execFile)
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const templateRoot = path.resolve(process.env.SZTU_TEMPLATE_DIR || path.join(root, "..", "Thesis"))
const fixtureSource = path.join(root, "tests", "fixtures", "bibtex-rendering.bib")
const goldenPath = path.join(root, "tests", "fixtures", "bibtex-rendering.golden.json")
const workDir = path.join(root, "tmp", "bibtex-rendering")
const styleName = "gbt7714-numerical.bst"

async function findBibtex() {
  if (process.env.SZTU_BIBTEX_PATH) return process.env.SZTU_BIBTEX_PATH
  const programData = process.env.ProgramData || "C:\\ProgramData"
  const engineRoot = path.join(programData, "SZTU-Docs", "engine")
  const entries = await readdir(engineRoot).catch(() => [])
  for (const entry of entries) {
    const candidate = path.join(engineRoot, entry, "texlive", "bin", "windows", "bibtex.exe")
    const found = await access(candidate).then(() => candidate, () => null)
    if (found) return found
  }
  return "bibtex"
}

// Strip LaTeX commands but keep the punctuation the style emitted; the test
// applies the same normalization to both sides before comparing.
function latexToText(value) {
  return value
    .replace(/\\newblock/g, " ")
    .replace(/\\allowbreak/g, "")
    .replace(/\\url\{([^}]*)\}/g, "$1")
    .replace(/\\href\{[^}]*\}\{([^}]*)\}/g, "$1")
    .replace(/\\doi\{([^}]*)\}/g, "DOI: $1")
    .replace(/\\textendash/g, "-")
    .replace(/\\textemdash/g, "-")
    .replace(/\\textcopyright/g, "©")
    .replace(/\\&/g, "&")
    .replace(/\\%/g, "%")
    .replace(/\\_/g, "_")
    .replace(/\\[a-zA-Z]+\s*/g, "")
    .replace(/[{}]/g, "")
    .replace(/~+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
}

// The compiled PDF and the desktop preview are allowed to differ in case,
// spacing and full-width/half-width forms; they must not differ in wording,
// field order or punctuation. The normalization itself lives in the test:
// the golden file stores raw style output, and the test normalizes both sides
// with the same rules, so drift cannot silently pass.

const bibtex = await findBibtex()
const styleSource = path.join(templateRoot, styleName)
const styleSha256 = createHash("sha256").update(await readFile(styleSource)).digest("hex")
await mkdir(workDir, { recursive: true })
await copyFile(styleSource, path.join(workDir, styleName))
await copyFile(fixtureSource, path.join(workDir, "refs.bib"))

const source = await readFile(fixtureSource, "utf8")
const keys = [...source.matchAll(/@\w+\{([^,]+),/g)].map(match => match[1].trim())
await writeFile(
  path.join(workDir, "refs.aux"),
  ["\\relax", `\\citation{${keys.join(",")}}`, `\\bibstyle{${styleName.replace(/\.bst$/, "")}}`, "\\bibdata{refs}", ""].join("\n"),
  "utf8",
)

const environment = { ...process.env, BSTINPUTS: `.;${workDir}`, BIBINPUTS: `.;${workDir}` }
// bibtex.exe resolves its own texmf.cnf only when TEXMFROOT points at the
// portable TeX Live tree; without it, style and database files are skipped.
const texliveRoot = process.env.SZTU_TEXLIVE_ROOT
  || (path.basename(bibtex).toLowerCase() === "bibtex.exe"
    ? path.resolve(path.dirname(bibtex), "..", "..", "..")
    : null)
if (texliveRoot) {
  environment.TEXMFROOT = texliveRoot
  environment.TEXMFCNF = texliveRoot
  environment.TEXMFVAR = path.join(texliveRoot, "texmf-var")
}
await run(bibtex, ["refs"], { cwd: workDir, env: environment })

const bbl = (await readFile(path.join(workDir, "refs.bbl"), "utf8")).split("\\end{thebibliography}")[0]
const rendered = {}
const parts = bbl.split(/\\bibitem\[[^\]]*\]\{([^}]*)\}/)
for (let index = 1; index + 1 < parts.length; index += 2) {
  rendered[parts[index].trim()] = latexToText(parts[index + 1])
}

const missing = keys.filter(key => !rendered[key])
if (missing.length > 0) throw new Error(`bibtex produced no entry for: ${missing.join(", ")}`)

const golden = {
  $comment:
    "Generated by scripts/generate_bibtex_rendering_golden.mjs from the repository " +
    "GB/T 7714—2025 style. Do not edit by hand; regenerate after changing the style or the fixture.",
  style: styleName,
  style_sha256: styleSha256,
  entries: rendered,
}
await writeFile(goldenPath, `${JSON.stringify(golden, null, 2)}\n`, "utf8")
for (const key of keys) console.log(`${key}: ${rendered[key]}`)
console.log(`\nWrote ${path.relative(root, goldenPath)} (${keys.length} entries)`)
